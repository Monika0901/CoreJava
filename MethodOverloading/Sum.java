/*Overload sum() using different data types:
sum(int, int)
sum(float, float)*/

package MethodOverloading;

public class Sum {


    // Method to calculate sum of two int values
	public int sum( int a, int b) {
		return a+b ;
	}
	

    // Overloaded method to calculate sum of two float values

	public float sum(float a, float b) {
		return a+b;
	}
}
