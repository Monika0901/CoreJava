/* Overload a method multiply() to multiply:
two int values
two double values
*/

package MethodOverloading;

public class Multiplication {

	//method for two int values
	public int Multiply(int a, int b) {
		return a*b;
	}
	
	//method for two double values
	public double Multiply(double a, double b) {
		return a*b;
	}
}
